/**
 * Splits any string into semantic phrases.
 * If known, uses semantic split dictionary. Otherwise, dynamically splits before
 * conjunctions like "และ" (and) or "หรือ" (or) without breaking words mid-syllable.
 */
export function splitSemanticPhrases(text: string): string[] {
  if (!text) return [];
  if (SEMANTIC_SPLITS[text]) {
    return SEMANTIC_SPLITS[text];
  }

  // Lookahead split: break right before conjunctions "และ" or "หรือ" or "พร้อม" or parentheses
  if (text.includes('และ') || text.includes('หรือ') || text.includes('(')) {
    const parts = text
      .split(/(?=[(])|(?<=[)])|(?=(?:และ|หรือ|พร้อม))/g)
      .map((p) => p.trim())
      .filter(Boolean);
    if (parts.length > 1) {
      return parts;
    }
  }

  return [text];
}

/**
 * Helper to render semantic phrases wrapped in `inline-block`.
 * Only when screen/window width requires wrapping, the browser breaks at
 * natural phrase boundaries (e.g. before "และ" or "หรือ") rather than mid-word.
 */
export function renderSemantic(text: string, spanClassName: string = '') {
  const phrases = splitSemanticPhrases(text);
  if (phrases.length <= 1) {
    return <span className={`inline-block ${spanClassName}`.trim()}>{text}</span>;
  }
  return phrases.map((phrase, idx) => (
    <React.Fragment key={idx}>
      {idx > 0 && ' '}
      <span className={`inline-block ${spanClassName}`.trim()}>{phrase}</span>
    </React.Fragment>
  ));
}

export interface SemanticTextProps {
  text: string;
  className?: string;
  spanClassName?: string;
}

export const SemanticText: React.FC<SemanticTextProps> = ({
  text,
  className = '',
  spanClassName = '',
}) => {
  return <span className={className}>{renderSemantic(text, spanClassName)}</span>;
};
